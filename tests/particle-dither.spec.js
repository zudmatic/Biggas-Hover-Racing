import {test,expect} from '@playwright/test';
import {PNG} from 'playwright-core/lib/utilsBundle';
import {openPlayground,set,setState,vfx} from './helpers/playground.js';
const difference=(a,b)=>{const x=PNG.sync.read(a).data,y=PNG.sync.read(b).data;let total=0;for(let i=0;i<x.length;i+=4)total+=Math.abs(x[i]-y[i])+Math.abs(x[i+1]-y[i+1])+Math.abs(x[i+2]-y[i+2]);return total;};
const hide={style:'header,aside,#hud {visibility:hidden!important}'};
for(const backend of ['webgpu','webgl2'])test(`particle dither changes the paused frame without the flame: ${backend}`,async({page})=>{
 test.setTimeout(240000);
 const errors=await openPlayground(page,`backend=${backend}`);
 await setState(page,'turbo');
 for(const name of ['Llama','Motor','Brasas','Chispas lineales','Calor'])await set(page,'Propulsor · WebGPU',name,false);
 await set(page,'Escena','Cómic',false);
 await expect.poll(async()=>(await vfx(page))?.emitted??0,{timeout:60000}).toBeGreaterThan(100);
 await set(page,'Tiempo','Pausa',true);
 await set(page,'Propulsor · WebGPU','Trama','Apagado');await page.waitForTimeout(250);
 const canvas=page.locator('main canvas');const off=await canvas.screenshot(hide);
 await set(page,'Propulsor · WebGPU','Trama','Dither');await page.waitForTimeout(250);
 const on=await canvas.screenshot(hide);expect(difference(on,off)).toBeGreaterThan(1000);
 await page.screenshot({path:`test-results/dither-${backend}.png`});
 await set(page,'Propulsor · WebGPU','Trama','Apagado');await page.waitForTimeout(250);
 const restored=await canvas.screenshot(hide);
 expect(difference(restored,off)).toBeLessThan(difference(on,off)*.2);
 expect(errors).toEqual([]);
});
