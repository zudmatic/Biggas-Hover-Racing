import {test,expect} from '@playwright/test';
import {launchFromLobby,openFlightOptions} from './helpers/flight.js';

for(const viewport of [{width:1200,height:800},{width:390,height:844}])test(`pause groups controls and options at ${viewport.width}px`,async({page})=>{
 test.setTimeout(90000);await page.setViewportSize(viewport);await page.emulateMedia({reducedMotion:'reduce'});
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto('/simulator.html?vehicle=037');await launchFromLobby(page);
 const app=page.locator('.flight-app');await expect(app).toHaveAttribute('data-ready','true',{timeout:60000});
 await expect(page.locator('.flight-header')).toHaveCount(0);
 await expect(page.getByRole('button',{name:'Faros',exact:true})).toHaveCount(0);
 await page.keyboard.press('KeyF');await expect(app).toHaveAttribute('data-headlights','true');
 await page.keyboard.press('KeyF');await expect(app).toHaveAttribute('data-headlights','false');
 await page.keyboard.press('Escape');
 await expect(page.getByRole('button',{name:'Continuar',exact:true})).toBeFocused();
 const controls=page.locator('.flight-controls summary');await controls.focus();await controls.press('Space');
 await expect(page.locator('.flight-controls-list')).toBeVisible();
 await expect(page.locator('.flight-controls-list')).toContainText('Faros');
 await expect(page.locator('.flight-controls-list')).toContainText('Cambiar cámara');
 await controls.press('Enter');await expect(page.locator('.flight-controls-list')).toBeHidden();
 await openFlightOptions(page);const time=await app.getAttribute('data-time');
 await page.getByRole('button',{name:'Cambiar cámara'}).click();await expect(app).toHaveAttribute('data-camera','1');
 await page.getByRole('button',{name:'Iluminación nocturna'}).click();await expect(app).toHaveAttribute('data-lighting','night');
 await page.getByRole('button',{name:'Sonido',exact:true}).click();
 const volume=page.getByRole('slider',{name:'Volumen de música'});await volume.fill('45');await volume.press('ArrowRight');await expect(volume).toHaveValue('46');
 await volume.press('Escape');await expect(app).toHaveAttribute('data-phase','paused');
 await expect(page.locator('.sound-panel')).toBeHidden();
 await expect(app).toHaveAttribute('data-time',time);
 const hangar=page.getByRole('link',{name:'Ir al hangar'});await expect(hangar).toHaveAttribute('href',/spaceship.html\?vehicle=037&pilot=zud/);
 await hangar.scrollIntoViewIfNeeded();const box=await hangar.boundingBox();expect(box.x).toBeGreaterThanOrEqual(0);expect(box.x+box.width).toBeLessThanOrEqual(viewport.width);expect(box.y+box.height).toBeLessThanOrEqual(viewport.height);
 await page.getByLabel('Gráficos').focus();await page.keyboard.press('Escape');await expect(app).toHaveAttribute('data-phase','flying');await expect(page.locator('.flight-canvas')).toBeFocused();
 await expect(app).toHaveAttribute('data-camera','1');await expect(app).toHaveAttribute('data-lighting','night');
 await page.keyboard.press('Escape');const resume=page.getByRole('button',{name:'Continuar',exact:true});await expect(resume).toBeFocused();const resumeBox=await resume.boundingBox();expect(resumeBox.y).toBeGreaterThan(0);expect(resumeBox.y+resumeBox.height).toBeLessThan(viewport.height);
 expect(errors).toEqual([]);
});
